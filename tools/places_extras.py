"""Extra per-place data for the /places Worker pages (writes worker/places-extra.js; commit it):

  TC_SOURCE=/path/to/teslachargers-site/source/tc python3 tools/places_extras.py

- PH: phone number for each garage URL in this site's listings (tap-to-call on place pages).
- SC: every operational Tesla Supercharger in the UK [name, lat, lon, stalls, max kW].
- RC: every public rapid charger (50 kW+, other networks, operational) as [lat, lon], for counts near each place.
Charger data: teslachargers.co.uk source (Open Charge Map contributors, CC BY-SA 4.0, and Tesla's UK site list)."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sitelib import ROOT, garages
import enrich as E   # Superchargers and rapid chargers, filtered exactly as on the garage pages

R = E.R
PH = {g['url']: g['phone'] for g in garages() if g.get('url') and g.get('phone')}
SC = sorted([[R[i][1].replace('Tesla Supercharger ', '').strip() or R[i][1], round(R[i][5], 5), round(R[i][6], 5), R[i][16] or 0, R[i][15] or 0] for i in E.SUPER], key=lambda x: x[0])
RC = sorted([[round(R[i][5], 4), round(R[i][6], 4)] for i in E.RAPID])
js = '// Generated by tools/places_extras.py - do not edit by hand.\n' + ''.join(
    f'export const {k} = {json.dumps(v, ensure_ascii=False, separators=(",", ":"))};\n' for k, v in (('PH', PH), ('SC', SC), ('RC', RC)))
open(os.path.join(ROOT, 'worker', 'places-extra.js'), 'w', encoding='utf-8').write(js)
print(json.dumps({'phones': len(PH), 'superchargers': len(SC), 'rapid': len(RC), 'kb': len(js.encode()) // 1024}))
