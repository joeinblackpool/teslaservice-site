// Build worker/place-pop.js: rough populations for the place search (/places/find), so an ambiguous name
// like "Poulton" or "Newport" goes to the bigger town first (Poulton-le-Fylde, Newport in Wales).
//
//   npm i --prefix /tmp/atc all-the-cities@3.1.0
//   node tools/place_pop.mjs /tmp/atc/node_modules/all-the-cities
//
// Source: GeoNames via the all-the-cities package (places of 1,000+ people; CC BY 4.0). A place in
// worker/places-data.js gets a population when GeoNames has the same name within 6 km. Keys are the
// place's /places path (area/slug) or its /locations URL, so a rebuild of places-data.js keeps working.
// Idempotent: the same inputs give byte-identical output.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url'; import { createRequire } from 'node:module';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) { console.error('usage: node tools/place_pop.mjs /path/to/node_modules/all-the-cities'); process.exit(2); }
const cities = createRequire(import.meta.url)(path.resolve(src)).filter(c => c.country === 'GB' && c.population > 0);
const { A, P, LT } = await import(path.join(ROOT, 'worker', 'places-data.js'));

const norm = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, ' ').trim();
const RAD = Math.PI / 180;
const km = (a, b, c, d) => { const x = Math.sin((c - a) * RAD / 2), y = Math.sin((d - b) * RAD / 2); return 12742 * Math.asin(Math.sqrt(x * x + Math.cos(a * RAD) * Math.cos(c * RAD) * y * y)); };
const byName = new Map();
for (const c of cities) { const k = norm(c.name); if (!byName.has(k)) byName.set(k, []); byName.get(k).push(c); }
function pop(name, lat, lon) {
  const base = name.split(/\s*[(/]/)[0];
  let best = 0;
  for (const c of byName.get(norm(base)) || []) {
    const [lo, la] = c.loc.coordinates;
    if (km(lat, lon, la, lo) <= 6 && c.population > best) best = c.population;
  }
  return best;
}
const out = {};
for (const p of P) { const n = pop(p[0], p[2], p[3]); if (n) out[`${A[p[1]][1]}/${p[4]}`] = n; }
for (const t of LT) { const n = pop(t[0], t[2], t[3]); if (n) out[t[1]] = Math.max(out[t[1]] || 0, n); }
const keys = Object.keys(out).sort();
const body = '// Generated by tools/place_pop.mjs - do not edit by hand. Populations: GeoNames (CC BY 4.0) via all-the-cities.\n' +
  'export const POP = {' + keys.map(k => JSON.stringify(k) + ':' + out[k]).join(',') + '};\n';
fs.writeFileSync(path.join(ROOT, 'worker', 'place-pop.js'), body);
console.log(JSON.stringify({ places: keys.length, bytes: body.length }));
