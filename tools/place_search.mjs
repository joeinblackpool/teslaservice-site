// Build worker/place-search.js: the index behind /places/find (the finder's town and village search), so a
// search does almost no work on the live Worker. Run after tools/places.py or tools/place_pop.mjs:
//   node tools/place_search.mjs
// SX maps the first word of a normalised place name to the places that start with it: a number k >= 0 is
// P[k]; k < 0 is the /locations town LT[-k - 1]. LTA[i] is the council area (index into A) of LT[i].
// Idempotent: the same places-data.js gives byte-identical output.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { P, LT } = await import(path.join(ROOT, 'worker', 'places-data.js'));
const { qnorm } = await import(path.join(ROOT, 'worker', 'qnorm.js'));
const RAD = Math.PI / 180;
const d2 = (a, b, c, d) => { const y = c - a, x = (d - b) * Math.cos(a * RAD); return x * x + y * y; };
const SX = {};
const add = (name, k) => { const w = qnorm(name.split(/\s*[(/]/)[0]).split(' ')[0]; if (!w) return; (SX[w] ||= []).push(k); };
P.forEach((p, i) => add(p[0], i));
LT.forEach((t, i) => add(t[0], -i - 1));
const LTA = LT.map(t => { let best = Infinity, ai = 0; for (const p of P) { const q = d2(t[2], t[3], p[2], p[3]); if (q < best) { best = q; ai = p[1]; } } return ai; });
const keys = Object.keys(SX).sort();
const body = '// Generated by tools/place_search.mjs - do not edit by hand.\n' +
  'export const SX = {' + keys.map(k => JSON.stringify(k) + ':' + JSON.stringify(SX[k])).join(',') + '};\n' +
  'export const LTA = ' + JSON.stringify(LTA) + ';\n';
fs.writeFileSync(path.join(ROOT, 'worker', 'place-search.js'), body);
console.log(JSON.stringify({ words: keys.length, bytes: body.length }));
